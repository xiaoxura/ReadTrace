// SaveCookiesIfCurrentSkey 凭据 CAS（缺陷 03）：仅当账号当前存储的 wr_skey
// 与 expectedSkey 一致时才把新凭据写入，否则不写。用于「结果到达时间不确定
// 的续期/自动登录」的写回路径，防止旧请求的响应覆盖等待期间发生的新登录或
// 换绑。事务内读出当前 cookie_enc → 解密取 wr_skey → 比对 → UPDATE。
//
// 边界处理：
//   - 返回 written=false（nil）表示「已变更/无法证明一致，未写入」。
//   - cookie_enc 解密失败（密钥轮换、损坏数据等）：读不出旧 skey 就无法
//     证明仍旧一致，视为「已变更」处理，宁可不写也不覆盖不明状态的凭据，
//     返回 false 与 nil，调用方只跳过写回，不算错误。
//   - 预期值与库中值都为空字符串（账号本来就没有 skey）视为一致，允许
//     一次全新写入（首次导入/自动登录的场景）。
func (s *Store) SaveCookiesIfCurrentSkey(id int64, expectedSkey string, cookies map[string]string) (bool, error) {
	tx, err := s.db.Begin()
	if err != nil {
		return false, err
	}
	defer tx.Rollback()
	var ckEnc []byte
	err = tx.QueryRow(`SELECT cookie_enc FROM accounts WHERE id = ?`, id).Scan(&ckEnc)
	if err == sql.ErrNoRows {
		return false, fmt.Errorf("账号不存在")
	}
	if err != nil {
		return false, err
	}
	if len(ckEnc) > 0 {
		current := map[string]string{}
		if err := s.openJSON(ckEnc, &current); err != nil {
			return false, nil
		}
		if current["wr_skey"] != expectedSkey {
			return false, nil
		}
	}
	ck, err := s.sealJSON(cookies)
	if err != nil {
		return false, err
	}
	if _, err := tx.Exec(`UPDATE accounts SET cookie_enc = ?, updated_at = ? WHERE id = ?`, ck, now(), id); err != nil {
		return false, err
	}
	if err := tx.Commit(); err != nil {
		return false, err
	}
	return true, nil
}

// SavePayload replaces the captured read template.
func (s *Store) SavePayload(id int64, payload map[string]any) error {
	pl, err := s.sealJSON(payload)
	if err != nil {
		return err
	}
	_, err = s.db.Exec(`UPDATE accounts SET payload_enc = ?, updated_at = ? WHERE id = ?`, pl, now(), id)
	return err
}

// AccountSecrets decrypts the cookie jar and payload template.
func (s *Store) AccountSecrets(id int64) (map[string]string, map[string]any, error) {
	var ckEnc, plEnc []byte
	err := s.db.QueryRow(`SELECT cookie_enc, payload_enc FROM accounts WHERE id = ?`, id).Scan(&ckEnc, &plEnc)
	if err == sql.ErrNoRows {
		return nil, nil, fmt.Errorf("账号不存在")
	}
	if err != nil {
		return nil, nil, err
	}
	cookies := map[string]string{}
	payload := map[string]any{}
	if len(ckEnc) > 0 {
		if err := s.openJSON(ckEnc, &cookies); err != nil {
			return nil, nil, fmt.Errorf("解密 Cookie 失败: %w", err)
		}
	}
	if len(plEnc) > 0 {
		if err := s.openJSON(plEnc, &payload); err != nil {
			return nil, nil, fmt.Errorf("解密模板失败: %w", err)
		}
	}
	return cookies, payload, nil
}

// DeleteAccount removes the account and its runs, statistics, schedules, pool,
// and sequence progress in one transaction.
func (s *Store) DeleteAccount(id int64) error {
	tx, err := s.db.Begin()
	if err != nil {
		return err
	}
	defer tx.Rollback()

	if _, err := tx.Exec(`DELETE FROM run_logs WHERE run_id IN (SELECT id FROM runs WHERE account_id = ?)`, id); err != nil {
		return err
	}
	if _, err := tx.Exec(`DELETE FROM runs WHERE account_id = ?`, id); err != nil {
		return err
	}
	if _, err := tx.Exec(`DELETE FROM run_statistics WHERE account_id = ?`, id); err != nil {
		return err
	}
	if _, err := tx.Exec(`DELETE FROM schedules WHERE account_id = ?`, id); err != nil {
		return err
	}
	if _, err := tx.Exec(`DELETE FROM pool_items WHERE account_id = ?`, id); err != nil {
		return err
	}
	if _, err := tx.Exec(`DELETE FROM settings WHERE key = ?`, fmt.Sprintf("sequence_pos_%d", id)); err != nil {
		return err
	}
	if _, err := tx.Exec(`DELETE FROM accounts WHERE id = ?`, id); err != nil {
		return err
	}
	return tx.Commit()
}

// DeletePayload removes the captured template without touching the account.
func (s *Store) DeletePayload(id int64) error {
	_, err := s.db.Exec(`UPDATE accounts SET payload_enc = NULL, updated_at = ? WHERE id = ?`, now(), id)
	return err
}

