const accountCols = `id, seq, name, vid, nickname, avatar, status, last_error, last_check_at,
	default_minutes, daily_goal_minutes, tick_seconds, read_speed, max_retries, retry_delay,
	book_id, book_title, chapter_id, chapter_title,
	mode, push_channel_id, created_at, updated_at,
	CASE WHEN payload_enc IS NOT NULL AND length(payload_enc) > 0 THEN 1 ELSE 0 END`

func scanAccount(sc interface{ Scan(...any) error }) (*Account, error) {
	var a Account
	var hasPayload int
	err := sc.Scan(&a.ID, &a.Seq, &a.Name, &a.Vid, &a.Nickname, &a.Avatar, &a.Status, &a.LastError,
		&a.LastCheckAt, &a.DefaultMinutes, &a.DailyGoalMinutes, &a.TickSeconds, &a.ReadSpeed, &a.MaxRetries, &a.RetryDelay,
		&a.BookID, &a.BookTitle, &a.ChapterID, &a.ChapterTitle,
		&a.Mode, &a.PushChannelID, &a.CreatedAt, &a.UpdatedAt,
		&hasPayload)
	if err != nil {
		return nil, err
	}
	a.HasPayload = hasPayload == 1
	return &a, nil
}

// ListAccounts returns all accounts ordered by creation time.
func (s *Store) ListAccounts() ([]Account, error) {
	rows, err := s.db.Query(`SELECT ` + accountCols + ` FROM accounts ORDER BY id ASC`)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []Account{}
	for rows.Next() {
		a, err := scanAccount(rows)
		if err != nil {
			return nil, err
		}
		out = append(out, *a)
	}
	return out, rows.Err()
}

// GetAccount returns one account.
func (s *Store) GetAccount(id int64) (*Account, error) {
	a, err := scanAccount(s.db.QueryRow(`SELECT `+accountCols+` FROM accounts WHERE id = ?`, id))
	if err == sql.ErrNoRows {
		return nil, nil
	}
	return a, err
}

// CreateAccount inserts an account with its encrypted secrets. seq is a
// display ID generated by this project: it is always the current maximum plus
// one, starting from 0.
func (s *Store) CreateAccount(a Account, cookies map[string]string, payload map[string]any) (int64, error) {
	if a.Status == "" {
		a.Status = "active"
	}
	if a.DefaultMinutes <= 0 {
		a.DefaultMinutes = 30
	}
	if a.TickSeconds <= 0 {
		a.TickSeconds = 30
	}
	a.ReadSpeed = clampReadSpeed(a.ReadSpeed)
	if a.RetryDelay <= 0 {
		a.RetryDelay = 30
	}
	if a.MaxRetries <= 0 {
		a.MaxRetries = 5
	}
	if a.Mode == "" {
		a.Mode = "sequence"
	}
	ck, err := s.sealJSON(cookies)
	if err != nil {
		return 0, err
	}
	pl, err := s.sealJSON(payload)
	if err != nil {
		return 0, err
	}
	if len(cookies) == 0 {
		ck = nil
	}
	if len(payload) == 0 {
		pl = nil
	}
	ts := now()
	// 建号与共享池归属迁移放进同一事务（缺陷 24）：旧无账号库升级时会跳过
	// 共享池迁移（migrateSharedPoolOwnership 需要至少一个账号），遗留的
	// account_id=0 行在创建首账号时在这里接管生效，无需等下次重启再迁移。
	// 顺带复用迁移主路径的合并+改归属逻辑（adoptSharedPoolOwnership），不
	// 另写一份；迁移失败则整个建号回滚，不留半套账号加半套池。
	tx, err := s.db.Begin()
	if err != nil {
		return 0, err
	}
	defer tx.Rollback()
	res, err := tx.Exec(`INSERT INTO accounts
		(seq, name, vid, nickname, avatar, cookie_enc, payload_enc, status, last_error, last_check_at,
		 default_minutes, daily_goal_minutes, tick_seconds, read_speed, max_retries, retry_delay, book_id, book_title, chapter_id, chapter_title,
		 mode, push_channel_id, created_at, updated_at)
		VALUES ((SELECT COALESCE(MAX(seq), -1) + 1 FROM accounts), ?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?,?)`,
		a.Name, a.Vid, a.Nickname, a.Avatar, ck, pl, a.Status, a.LastError, a.LastCheckAt,
		a.DefaultMinutes, a.DailyGoalMinutes, a.TickSeconds, a.ReadSpeed, a.MaxRetries, a.RetryDelay, a.BookID, a.BookTitle,
		a.ChapterID, a.ChapterTitle, a.Mode, a.PushChannelID, ts, ts)
	if err != nil {
		return 0, err
	}
	id, err := res.LastInsertId()
	if err != nil {
		return 0, err
	}
	// 首账号创建时 MIN(id) 即为新账号；如果早已有账号而 0 号共享行仍在
	// （理论上不会，迁移在 Open 时已完成），同样安全地归属到第一个账号。
	if err := migrateSharedPoolOwnership(tx); err != nil {
		return 0, fmt.Errorf("归属共享书池遗留条目失败: %w", err)
	}
	if err := tx.Commit(); err != nil {
		return 0, err
	}
	return id, nil
}

// UpdateAccount updates editable settings.
func (s *Store) UpdateAccount(a Account) error {
	_, err := s.db.Exec(`UPDATE accounts SET
		name = ?, default_minutes = ?, daily_goal_minutes = ?, tick_seconds = ?, read_speed = ?, max_retries = ?, retry_delay = ?,
		book_id = ?, book_title = ?, chapter_id = ?, chapter_title = ?,
		mode = ?, push_channel_id = ?, updated_at = ?
		WHERE id = ?`,
		a.Name, a.DefaultMinutes, a.DailyGoalMinutes, a.TickSeconds, clampReadSpeed(a.ReadSpeed), a.MaxRetries, clampRetryDelay(a.RetryDelay),
		a.BookID, a.BookTitle, a.ChapterID, a.ChapterTitle,
		a.Mode, a.PushChannelID, now(), a.ID)
	return err
}

// clampRetryDelay keeps the retry interval in a sane range.
func clampRetryDelay(v int) int {
	if v <= 0 {
		return 15
	}
	if v > 600 {
		return 600
	}
	return v
}

// clampReadSpeed keeps the reading speed (words per minute) in a sane range:
// 0/未填 回落默认 300，上限 3000。下限由 API 校验（>=10），非整数值在
// decode 阶段已不可达。
func clampReadSpeed(v int) int {
	if v <= 0 {
		return 300
	}
	if v > 3000 {
		return 3000
	}
	return v
}

